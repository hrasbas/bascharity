/* 002 — SHOW ARTICLE */
function showShoppingArticle(articleId) {
  const article = shoppingArticles.find(item => item.id === Number(articleId));

  if (!article) return;

  const container = document.getElementById("shoppingArticleContent");

  if (!container) return;

  container.innerHTML = article.content;

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}


/* 003 — CREATE ARTICLE BUTTONS */
function createShoppingArticleButtons(containerId) {
  const container = document.getElementById(containerId);

  if (!container) return;

  container.innerHTML = "";

  shoppingArticles.forEach(article => {

    const button = document.createElement("button");

    button.type = "button";
    button.className = "shopping-article-button";
    button.textContent = article.title;

    button.addEventListener("click", function () {
      showShoppingArticle(article.id);
    });

    container.appendChild(button);
  });
}


/* 004 — AUTO INITIALIZATION */
document.addEventListener("DOMContentLoaded", function () {

  if (document.getElementById("shoppingArticleButtons")) {
    createShoppingArticleButtons("shoppingArticleButtons");
  }

});
